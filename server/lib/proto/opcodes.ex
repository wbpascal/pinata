  @doc "The client opcodes of a part (#{length(@zone)} for Zone, #{length(@world_manager)} for WorldManager)."
  @spec client(String.t()) :: [0..0xFFFF]
  def client("Zone"), do: @zone
  def client("WorldManager"), do: @world_manager
  def client(_part), do: []

  @doc "Whether the opcode belongs to the client packets of the part (the label of `Net.Connection`); false for any other part."
  @spec client?(String.t(), 0..0xFFFF) :: boolean()
  def client?("Zone", opcode), do: opcode in @zone
  def client?("WorldManager", opcode), do: opcode in @world_manager
  def client?(_part, _opcode), do: false

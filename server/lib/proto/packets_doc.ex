defmodule Proto.PacketsDoc do
  @moduledoc "Renders `docs/technical/packets.md` from the packet definitions."

  @header """
  # Packets

  Generated by `mix pinata.packets_doc` from the definitions in `lib/proto/packets/`. Do not edit.

  | Opcode | Official name | Module | Payload bytes | Fields |
  |---|---|---|---|---|
  """

  @doc "The whole file, ending in one newline."
  @spec render() :: String.t()
  def render, do: @header <> Enum.map_join(Proto.Packets.all(), &row/1)

  defp row(mod) do
    %{size: size, fields: fields} = mod.__packet__()
    opcode = mod.opcode() |> Integer.to_string(16) |> String.pad_leading(4, "0")
    name = mod |> Module.split() |> List.last() |> Macro.underscore() |> String.upcase()
    fields = if fields == [], do: "none", else: Enum.map_join(fields, "; ", fn {n, t} -> "`#{n}: #{t}`" end)
    "| `0x#{opcode}` | `NC_#{name}` | `#{inspect(mod)}` | #{size} | #{fields} |\n"
  end
end

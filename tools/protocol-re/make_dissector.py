def selftest():
    import struct
    try:
        from lupa import lua52, lua54
    except ImportError:
        sys.exit("selftest needs lupa: python3 -m venv v && v/bin/pip install lupa && v/bin/python make_dissector.py --selftest")
    src = open(OUT, encoding="ascii").read()
    docs = load_docs()

    def frame(body):
        return (bytes([len(body)]) if len(body) < 256 else b"\0" + struct.pack("<H", len(body))) + body

    seed, pw = 0x1234, b"secret"
    login = struct.pack("<H", 0x0C5A) + b"tester".ljust(256, b"\0") + b"\0" * 4 + pw.ljust(36, b"\0") + b"\0" * 20
    ver = struct.pack("<H", 0x0C65) + b"20151116141627".ljust(64, b"\0")
    e1, i1 = xor(ver, seed % 499)
    e2, i2 = xor(login, i1)
    e3, _ = xor(struct.pack("<H", 0x0804), i2)
    worlds = b"".join(bytes([i]) + f"World{i}".encode().ljust(16, b"\0") + b"\x06" for i in range(2))
    gen_op = next(op for op, s in sorted(docs["layouts"]["wm"][S2C].items())
                  if ("wm", op, S2C) not in docs["packets"] and op not in docs["pdb"] and s[0]["size"] and s[0]["fields"] and op not in (0x0807,))
    gen_size = docs["layouts"]["wm"][S2C][gen_op][0]["size"]
    zone_pre, _ = xor(struct.pack("<H", 0x0806), 0)
    C, S = "10.0.0.2", "10.0.0.1"
    frames = [  # (src, sport, dst, dport, tcp payload)
        (S, 9010, C, 50000, frame(struct.pack("<HH", 0x0807, seed))),
        (C, 50000, S, 9010, frame(e1)),
        (C, 50000, S, 9010, frame(e2) + frame(e3)),          # long form + two PDUs in one segment
        (S, 9010, C, 50000, frame(struct.pack("<HB", 0x0C0A, 2) + worlds) + frame(struct.pack("<H", 0xFFF0) + b"xy")),
        (S, 9110, C, 50001, frame(struct.pack("<H", gen_op) + b"\0" * (gen_size + 3))),
        (C, 50002, S, 9210, frame(zone_pre)),               # zone 0x0806 before the seed
    ]
    for name, rt in (("Lua 5.2", lua52), ("Lua 5.4", lua54)):
        L = rt.LuaRuntime(encoding=None)
        F = L.execute(src)
        assert bytes(F.XOR[i] for i in range(499)) == XOR499
        dec, nxt = F.decrypt(e1, seed % 499)
        assert dec == ver and nxt == i1, name
        conv = L.table()
        assert F.track(conv, True, e1) is None
        F.track(conv, False, struct.pack("<HH", 0x0807, seed))
        assert F.track(conv, True, e1) == seed % 499 and F.track(conv, True, e2) == i1
        r = F.decode(b"login", True, 0x0C5A, login[2:], False)
        labels = [n.label for n in r.nodes.values()]
        assert b'user_id: "tester"' in labels and b"password: ********" in labels and not list(r.issues.values()), labels
        r = F.decode(b"login", True, 0x0C5A, login[2:], True)
        assert b'password: "secret"' in [n.label for n in r.nodes.values()]
        r = F.decode(b"login", False, 0x0C0A, (struct.pack("<B", 2) + worlds), False)
        w = list(r.nodes.values())[1]
        assert w.label == b"worlds: 2 x WORLD" or w.label.endswith(b"2 x WORLD"), w.label
        assert list(w.children.values())[1].children[2].label == b'world_name: "World1"'
        assert F.decode(b"login", False, 0x0C0A, b"\x05", False).issues[1].kind == b"size"
        assert F.decode(b"login", False, 0xFFF0, b"", False).issues[1].kind == b"unknown"
        # pdb2017 fallback (C02), as in pcap_decode's selftest
        pop = next(o for o, v in sorted(docs["pdb"].items()) if ("zone", o, S2C) not in docs["packets"]
                   and v["size"] > 0 and not v["variable"])
        r = F.decode(b"zone", False, pop, bytes(docs["pdb"][pop]["size"]), False)
        assert r.source == b"pdb2017" and not list(r.issues.values()), pop
        # glue, through the mock API: first pass in order, then re-dissection in reverse order must match
        L.execute(MOCK)
        L.globals().P = L.execute(src + "\nreturn proto")
        assert set(L.globals().REG.keys()) == {9010, 9110, 9210, 9212, 9214, 9216}
        run = L.globals().run_frame
        first = [run(i, *f, False) for i, f in enumerate(frames)]
        again = [run(i, *f, True) for i, f in reversed(list(enumerate(frames)))][::-1]
        assert first == again, name
        out = b"\n".join(log for log, _ in first)
        for want in (b"fiesta.xor_index=" + str(seed % 499).encode(), b"fiesta.opcode=3162", b"password: ********",
                     b"fiesta.xor_index=" + str(i2).encode(), b"fiesta.opcode=2052", b'world_name: "World1"',
                     b"EXPERT fiesta.unknown_opcode unknown opcode 0xFFF0", b"(guess)",
                     b"EXPERT fiesta.size_mismatch payload " + str(gen_size + 3).encode() + b" bytes matches no send site",
                     b"EXPERT fiesta.no_seed", b"TEXT Fiesta zone C->S (encrypted, 2 bytes)"):
            assert want in out, (name, want)
        assert first[2][1].count(b"C->S") == 2 and first[3][1].startswith(b"Fiesta: S->C 0x0C0A"), first[2][1]
        assert all(pw not in t for t in L.globals().TABS.values()) and pw not in out
        print(f"{name}: OK")
    print("selftest OK")



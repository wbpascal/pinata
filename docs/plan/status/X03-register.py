#!/usr/bin/env python3
"""X03 wrapper around X01's bug-register generator (docs/plan/status/X01-register.py, left unchanged).

Adds to X01's sources and marks:
  - X02's bug table (docs/review/confidence.md §5, X02-B1 … B12) as its own group, with the reachability of
    docs/knowledge/X02.md §3 in the Evidence column;
  - a group for D08 (DB server process layer), which X01's GROUPS predates (its rows were dropped);
  - the register entries an X02 re-check or a follow-up item (Z31, Z32, W06, D08) changed (README §5.9).

usage (repo root):  python3 -I docs/plan/status/X03-register.py write   # rewrite README §6.1
                    python3 -I docs/plan/status/X03-register.py md      # print the register
"""
import sys

SRC = 'docs/plan/status/X01-register.py'
src = open(SRC, encoding='utf-8').read()
SPLIT = "if sys.argv[1] in ('md', 'write'):"
head, tail = src.split(SPLIT, 1)
tail = SPLIT + tail

# 1. X01's collection pass, with confidence.md added to the scanned files.
OLD = "files.append('docs/protocol/capture-validation.md')"
assert OLD in head
head = head.replace(OLD, OLD + "\nfiles.append('docs/review/confidence.md')   # X02-B1 … B12 (added by X03)")
mode = sys.argv[1] if len(sys.argv) > 1 else 'md'
ns = {'__name__': 'x01_register'}
argv = sys.argv
sys.argv = [SRC, 'none']
exec(compile(head, SRC, 'exec'), ns)
sys.argv = [SRC, mode]

# 2. Groups: D08 after the inferred procedures, X02 at the end.
G = ns['GROUPS']
i = [g[0] for g in G].index('Database (inferred procedures)')
G.insert(i + 1, ('DB server process layer (D08; Account, AccountLog, Character, GameLog)', ['D08']))
G.append(('Found by the confidence review (X02; WM, Zone, Character)', ['X02']))

# 3. Marks added by X03 (README §5.9 rows with Source X02 / W06 / D08).
ns['SUPERSEDED'].update({
    'Z01-B3': ('Extended', 'X02 Q3: also no reply for a wing whose attribute class is not 13; SAVE is further gated by vt 0xa78 `so_ply_IsLink_In_MapAndSendErrorMsg`; the 0x1142 of FLY is confirmed (E32)'),
    'Z01-B6': ('Narrowed', 'X02 T2 / Q5: the Character server never reads the appended `buylot`, so no DB row changes (the zone\'s lot runs ahead of the DB until a later ITEMDB message writes that stack); without item 0x9C9 in cell 0 the zone neither forwards nor answers'),
    'Z04-B4': ('Superseded', 'X02 V2 / E37: `sp_ItemDropOK` FUN_0052b060 re-reads the lot and calls `ii_DropLot` FUN_00529c20 when the stack grew while the drop confirmation was open: latent, not dead; that path holds X02-B9'),
    'W03-B3': ('Extended', 'W06 §1.3: the answer side 0x7463 copies the DB notice unbounded too (W06-B6; academy twin W06-B1)'),
    'D05-B7': ('Narrowed', 'D08 §1.3: `DAT_00656a3c` is `m_bStopMainThread`, which the main thread reads: 0x2803 does stop the GameLog server (D08-B2); the missing authentication stands'),
})

# 4. X02 reachability (docs/knowledge/X02.md §3) appended to the Evidence column.
REACH = {
    'X02-B1': 'latent', 'X02-B2': 'latent', 'X02-B3': 'needs a lost WM session', 'X02-B4': 'latent',
    'X02-B5': 'latent', 'X02-B6': 'latent', 'X02-B7': 'latent', 'X02-B8': 'normal play (with a `KQItem.shn` item)',
    'X02-B9': 'latent', 'X02-B10': 'crafted packet', 'X02-B11': 'failed send to a third party',
    'X02-B12': 'normal play',
}
ev0 = ns['evidence']
def evidence(cells, i=''):
    e = ev0(cells, i)
    return e + '; ' + REACH[i] if i in REACH else e
ns['evidence'] = evidence

# 5. Link to confidence.md relative to docs/pseudocode/README.md.
OLD = ".replace('docs/protocol/', '../protocol/')"
assert OLD in tail
tail = tail.replace(OLD, OLD + ".replace('docs/review/', '../review/')")
# 6. Begin marker names this wrapper (X01's script alone drops X02-B1 … B12 and D08-B1 … B12).
OLD = "i, j = doc.index(a) + len(a), doc.index(b)"
assert OLD in tail
tail = tail.replace(OLD, "na = '<!-- register:begin (generated by docs/plan/status/X03-register.py, which runs X01-register.py) -->\\n'; "
                    "doc = doc.replace(a, na); a = na; " + OLD)
# 7. X02 rows cite confidence.md sections; prefix them so they do not read as README §3 / §4.
OLD = "{c[0]} ({link}"
assert OLD in tail
tail = tail.replace(OLD, "{re.sub(r'\\(§', '(confidence.md §', c[0]) if i.startswith('X02-') else c[0]} ({link}")
exec(compile(tail, SRC, 'exec'), ns)
sys.argv = argv

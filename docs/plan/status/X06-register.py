#!/usr/bin/env python3
"""X06 wrapper around X04's bug-register generator (docs/plan/status/X04-register.py, which runs X03-register.py and
X01-register.py; all left unchanged).

Runs X04's wrapper in `md` mode and post-processes its rows for P02's capture batch 4 (captures s37b, s38, s24;
capture-validation §22-§25):
  1. the Evidence column of P02-B33 ... B40 (X04's P02_EV stops at P02-B32): *(captured)* with every § of the capture
     the first table of capture-validation §12 cites, plus the part that stays deduced;
  2. the second-table row "P02-B36 / D04-B13" (§25.9), which X04's parser skips (two IDs in one cell): §25.9 joined
     into both entries;
  3. Z07-B2: the captured field is unwritten but happened to hold 0, so the evidence is qualified;
  4. the README §5.9 mark added by X06: W05-B25 (Extended by P02-B35);
  5. cross notes (Handler column, "linked: ..."): P02-B35 <-> W05-B25, P02-B37 <-> D04-B5.

usage (repo root):  python3 -I docs/plan/status/X06-register.py write   # rewrite README §6.1
                    python3 -I docs/plan/status/X06-register.py md      # print the register
"""
import io, re, sys, contextlib, collections

README = 'docs/pseudocode/README.md'
MODE = sys.argv[1] if len(sys.argv) > 1 else 'md'

# --- run X04's wrapper (md) and capture its output and helpers ---------------------------------------------------
buf = io.StringIO()
argv = sys.argv
sys.argv = ['docs/plan/status/X04-register.py', 'md']
ns = {'__name__': 'x04_register'}
with contextlib.redirect_stdout(buf):
    exec(compile(open(sys.argv[0], encoding='utf-8').read(), sys.argv[0], 'exec'), ns)
sys.argv = argv
text = buf.getvalue()
caplink, split_cells = ns['caplink'], ns['split_cells']

# --- 1. P02's batch-4 rows: § of the capture (capture-validation §12, first table) ------------------------------
P02_EV = {
    'P02-B33': ['§22.2'],
    'P02-B34': ['§22.4'],
    'P02-B35': (['§22.5', '§23.3', '§25.9'], 'effect (no lost state) *(inferred)*'),
    'P02-B36': ['§22.5', '§23.5', '§25.9'],
    'P02-B37': ['§24.3'],
    'P02-B38': (['§25.4'], 'that the client ignores the second `0x2428` *(inferred)*'),
    'P02-B39': (['§25.4'], 'the script path *(inferred)*'),
    'P02-B40': ['§25.6'],
}

# --- 2. / 3. Evidence of other items' entries ------------------------------------------------------------------
EV_FIX = {
    'D04-B13': lambda: '*(captured)* (' + caplink(['§22.5', '§25.9']) + ')',
    'Z07-B2': lambda: '*(captured)* (' + caplink(['§24.4']) + ': `nLockIndex` unwritten; the stale word happened to be 0), code',
}

# --- 4. marks (README §5.9 rows "added by X06") ----------------------------------------------------------------
MARKS = {
    'W05-B25': ('Extended', 'P02 capture-validation §22.5 / §25.9: each `0x0C19` reaches the zone while the player is in its logout window and `so_banning` saves again: two of the four saves of P02-B35'),
}

# --- 5. cross notes ---------------------------------------------------------------------------------------------
NOTES = {
    'P02-B35': 'W05-B25 (the WM\'s double `0x0C19`, two of the saves)',
    'W05-B25': 'P02-B35 (each `0x0C19` runs a full save in the zone, captured)',
    'P02-B37': 'D04-B5 (the same `0x4812`, the item destruction on the Character server)',
    'D04-B5': 'P02-B37 (the same `0x4812` carries stale bytes, captured)',
}

out, changed = [], collections.Counter()
for line in text.split('\n'):
    m = re.match(r'^\| ([A-Z]\d{2}-B\d+[a-z]?) \|', line)
    if not m or m.group(1) not in set(P02_EV) | set(EV_FIX) | set(MARKS) | set(NOTES):
        out.append(line); continue
    i = m.group(1)
    c = split_cells(line.strip()[1:-1])          # ID, handler, beh, eff, intent, ev, owner
    if len(c) != 7:
        c = [x.strip() for x in line.strip()[1:-1].split(' | ')]
    if len(c) != 7:
        print('BAD', i, len(c), file=sys.stderr); out.append(line); continue
    if i in P02_EV:
        v = P02_EV[i]
        secs, extra = (v if isinstance(v, tuple) else (v, ''))
        c[5] = f'*(captured)* ({caplink(secs)})' + (', ' + extra if extra else '')
        changed['p02-evidence'] += 1
    if i in EV_FIX:
        c[5] = EV_FIX[i]()
        changed['ev-fix'] += 1
    if i in MARKS:
        mk, note = MARKS[i]
        c[2] = f"**{mk}** ({note}; [§5.9](#59-bug-register-entries-a-later-item-changed)): " + c[2]
        changed['mark'] += 1
    if i in NOTES:
        c[1] = c[1] + '; linked: ' + NOTES[i]
        changed['note'] += 1
    out.append('| ' + ' | '.join(c) + ' |')
text = '\n'.join(out)

for i in list(P02_EV) + list(EV_FIX) + list(MARKS) + list(NOTES):
    if not re.search(r'^\| ' + re.escape(i) + r' \|', text, re.M):
        print('MISSING', i, file=sys.stderr)
print('x06 changes', dict(changed), file=sys.stderr)

if MODE == 'md':
    print(text)
elif MODE == 'write':
    doc = open(README, encoding='utf-8').read()
    m = re.search(r'<!-- register:begin [^\n]*-->\n', doc)
    a = '<!-- register:begin (generated by docs/plan/status/X06-register.py, which runs X04-register.py, X03-register.py and X01-register.py) -->\n'
    j = doc.index('<!-- register:end -->')
    open(README, 'w', encoding='utf-8').write(doc[:m.start()] + a + text.rstrip('\n') + '\n\n' + doc[j:])
